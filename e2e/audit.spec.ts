test('controls, overrides and undo', async ({ page }) => {
  await newAudit(page)
  await importFile(page, { name: 'hand.csv', text: HAND }, 7)
  await page.getByLabel('Flag at score').fill('75')
  await expect(kpi(page, 'Spend at risk')).toContainText('$0')
  await page.getByLabel('Flag at score').fill('40')
  await expect(kpi(page, 'Spend at risk')).toContainText('$200')
  await tab(page, 'Placements')
  await row(page, 'bad.example').getByRole('button', { name: 'Allow' }).click()
  await expect(row(page, 'bad.example').getByRole('button', { name: 'Reset allow' })).toBeVisible()
  await row(page, 'clean2.example').getByRole('button', { name: 'Block' }).click()
  await expect(row(page, 'clean2.example').locator('.score-pill')).toHaveText('100')
  await page.keyboard.press('Control+z')
  await expect(row(page, 'clean2.example').getByRole('button', { name: 'Block' })).toBeVisible()
  await page.getByRole('radio', { name: /^Overrides/ }).click()
  await expect(page.locator('table.placements tbody tr')).toHaveCount(1)
  await page.getByRole('radio', { name: /^All/ }).click()
  await page.keyboard.press('/')
  await page.keyboard.type('clean3')
  await expect(page.locator('table.placements tbody tr')).toHaveCount(1)
})

