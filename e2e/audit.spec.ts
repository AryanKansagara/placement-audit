test('snapshots: compare shows what still spends, and delete can be undone', async ({ page }) => {
  await newAudit(page)
  await importFile(page, { name: 'hand.csv', text: HAND }, 7)
  await page.getByRole('button', { name: 'Save snapshot' }).click()
  await tab(page, 'Data')
  await importFile(page, { name: 'next.csv', text: HAND.replace('$200.00', '$50.00').replace('bad.example,"40,000"', 'bad.example,"5,000"') }, 7)
  // One flagged placement, $50 of $650 = 7.7%.
  await expect(kpi(page, 'Spend at risk')).toContainText('7.7%')
  await page.getByRole('button', { name: 'Save snapshot' }).click()
  await tab(page, 'History')
  await expect(page.locator('.kpi', { hasText: 'Risk share' })).toContainText('−17.3 pts')
  await expect(page.locator('.kpi', { hasText: 'Leaking exclusions' })).toContainText('1')
  await expect(page.locator('.verdict')).toContainText('1 previously flagged placement is still taking spend')
  await page.getByRole('button', { name: 'Delete', exact: true }).first().click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete snapshot' }).click()
  await expect(page.locator('.kpi', { hasText: 'Leaking exclusions' })).toHaveCount(0)
  await page.locator('.toast', { hasText: 'Snapshot deleted' }).getByRole('button', { name: 'Undo' }).click()
  await expect(page.locator('.kpi', { hasText: 'Leaking exclusions' })).toBeVisible()
})

