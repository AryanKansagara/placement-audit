import { expect, HAND, importFile, keys, kpi, newAudit, saved, tab, test } from './fixtures'

for (const [id, name] of [['northwind', 'Northwind Cloud: B2B native'], ['lumen', 'Lumen Streaming: CTV + in-app'], ['harbor', 'Harbor & Pine: retail display (ROAS)']]) {
  test(`sample ${id}: every tab and the report open`, async ({ page }) => {
    await page.goto(`/app?sample=${id}`)
    await expect(page.getByRole('heading', { name, level: 1 })).toBeVisible()
    await expect(page.locator('.badge.synthetic')).toBeVisible()
    await expect(kpi(page, 'Spend at risk').locator('b')).toHaveText(/^\$[1-9]/)
    await page.getByRole('button', { name: 'Preview exclusions' }).click()
    await expect(page.locator('.what-if-note')).toContainText('moves to clean placements')
    await page.keyboard.press('2')
    await expect(page.locator('table.placements')).toBeVisible()
    await page.keyboard.press('3')
    await expect(page.locator('.pace-card').first()).toBeVisible()
    await page.keyboard.press('4')
    await expect(page.locator('.code pre')).toContainText('domain')
    await page.keyboard.press('5')
    await expect(page.locator('.verdict')).toBeVisible()
    await page.keyboard.press('6')
    await expect(page.getByRole('heading', { name: 'Import reports' })).toBeVisible()
    await page.keyboard.press('p')
    await expect(page.getByRole('heading', { name: 'Summary' })).toBeVisible()
  })
}

test('sample CSV round trip: the download imports into a new audit with the same placements', async ({ page }) => {
  await page.goto('/app?sample=northwind&tab=placements')
  await expect(page.locator('table.placements')).toBeVisible()
  const before = await keys(page)
  await tab(page, 'Data')
  const f = await saved(page, () => page.getByRole('button', { name: 'Download sample CSV' }).click())
  await importFile(page, { name: f.name, text: f.text }, f.text.trim().split('\n').length - 1)
  await expect(page.getByRole('heading', { name: 'My campaign audit' })).toBeVisible()
  await tab(page, 'Placements')
  expect(await keys(page)).toEqual(before)
})

test('workspace: rename, delete with undo, JSON export', async ({ page }) => {
  await newAudit(page)
  await importFile(page, { name: 'hand.csv', text: HAND }, 7)
  await page.goto('/app')
  await page.getByRole('button', { name: 'Rename' }).click()
  await page.getByLabel('Project name').fill('Autumn push')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('link', { name: 'Autumn push' })).toBeVisible()
  await page.goto('/settings')
  const out = await saved(page, () => page.getByRole('button', { name: 'Export all my data (JSON)' }).click())
  const json = JSON.parse(out.text)
  expect(json.projects[0].name).toBe('Autumn push')
  expect(json.projects[0].dataset.rows).toHaveLength(7)
  await page.goto('/app')
  await page.getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete audit' }).click()
  await expect(page.getByRole('link', { name: 'Autumn push' })).toHaveCount(0)
  await page.locator('.toast').getByRole('button', { name: 'Undo' }).click()
  await page.getByRole('link', { name: 'Autumn push' }).click()
  await expect(kpi(page, 'Spend audited')).toContainText('$800')
})

test('settings: new audits use the saved defaults', async ({ page }) => {
  await page.goto('/settings')
  await page.getByLabel('Flag at risk score').fill('75')
  await page.getByRole('radio', { name: 'Dark' }).click()
  await newAudit(page)
  await importFile(page, { name: 'hand.csv', text: HAND }, 7)
  await expect(page.getByLabel('Flag at score')).toHaveValue('75')
  await expect(kpi(page, 'Spend at risk')).toContainText('$0')
})

